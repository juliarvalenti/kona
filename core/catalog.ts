import { existsSync } from "node:fs";
import { join, relative } from "node:path";
import type { AppletPackage } from "./load.ts";
import { REPO_ROOT } from "./load.ts";

/**
 * The applet catalog, generated from the packages that are actually installed.
 *
 * Per-applet prose used to be appended to the README, which made "add an
 * applet" a diff against a shared file — two applets, one conflict, over
 * paragraphs that have nothing to do with each other. So docs moved into the
 * package (`applets/<id>/README.md`) and this renders the index over them.
 * Nothing to append to; `kona docs` is always current, plugins included.
 */

const cell = (s: string) => s.replace(/\|/g, "\\|");

/** One line per applet: what it is, what it needs, where its docs live. */
export function catalogMarkdown(packages: AppletPackage[]): string {
  const rows = packages.map((p) => {
    const { def } = p;
    const readme = join(p.dir, "README.md");
    const where = existsSync(readme)
      ? p.source === "repo"
        ? `[docs](${relative(REPO_ROOT, readme)})`
        : "`README.md`"
      : "—";
    const labels = (def.labels ?? []).map((l) => `\`${l}\``).join(" ");
    return `| \`${def.id}\` | ${cell(def.title)} | ${cell(def.summary ?? "")} | ${labels} | ${where} |`;
  });
  const needs = packages
    .filter((p) => p.def.requires?.length)
    .map((p) => `- \`${p.def.id}\` — ${p.def.requires!.join("; ")}`);

  return [
    `# Applets (${packages.length})`,
    "",
    "Generated by `kona docs` from the applets this machine has loaded.",
    "",
    "| id | title | what it is | labels | docs |",
    "| --- | --- | --- | --- | --- |",
    ...rows,
    ...(needs.length ? ["", "## What they need", "", ...needs] : []),
    "",
  ].join("\n");
}

/** The plain-text listing `kona ls` prints. */
export function catalogLines(packages: AppletPackage[]): string[] {
  const width = Math.max(...packages.map((p) => p.def.id.length), 0);
  return packages.map((p) => {
    const tag = p.source === "repo" ? "" : `  (${p.source === "link" ? "linked" : "plugin"})`;
    return `${p.def.id.padEnd(width)}  ${p.def.summary ?? ""}${tag}`;
  });
}

/**
 * The launcher filter: which applets match what you have typed. Matches title,
 * id and summary so "mail" finds Email and "cron" finds Workflows, and ignores
 * case and surrounding space. An empty query matches everything — the launcher
 * is the same code path filtered or not.
 */
export function filterApplets<T extends { id: string; title: string; summary?: string }>(
  applets: T[],
  query: string,
): T[] {
  const q = query.trim().toLowerCase();
  if (!q) return applets;
  return applets.filter((a) =>
    `${a.title} ${a.id} ${a.summary ?? ""}`.toLowerCase().includes(q),
  );
}
